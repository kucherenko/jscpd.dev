/**
 * The rules behind the trending numbers, with no file system or jscpd in
 * them: what counts as code, how clone pairs become findings, how a path is
 * classified, and the calendar helpers. trending-scan.mjs applies them while
 * measuring, trending-lib.mjs while deriving the site's data files.
 */

export const round2 = (n) => typeof n === 'number' ? Math.round(n * 100) / 100 : n

// A repository with fewer code files than this gets no code percentage on
// the pages: one copied file would swing it by tens of points.
export const MIN_CODE_FILES = 20

// The raw scan: what the archive has measured since 2026-09-01.
export const ALL_IGNORE = [
  '**/node_modules/**', '**/vendor/**', '**/third_party/**', '**/dist/**', '**/build/**',
  '**/*.min.js', '**/*.map', '**/package-lock.json', '**/pnpm-lock.yaml'
]

// Programming-language formats, by the names `jscpd --list` prints. Markup,
