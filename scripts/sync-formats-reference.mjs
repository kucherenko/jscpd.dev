#!/usr/bin/env node
/**
 * Writes content/4.reference/5.supported-formats.md from the FORMATS.md of a
 * jscpd release (the file the tokenizer tests check against), so the format
 * tables cannot drift:
 *
 *   node scripts/sync-formats-reference.mjs path/to/FORMATS.md 5.4.0
 */
import { readFileSync, writeFileSync } from 'node:fs'

const [file, version = ''] = process.argv.slice(2)
if (!file) { console.error('usage: sync-formats-reference.mjs FORMATS.md [version]'); process.exit(1) }
let body = readFileSync(file, 'utf8')
// drop the H1 and anything before the first H2; the page has its own lead
body = body.slice(body.indexOf('\n## '))
// the shebang section links to itself with an anchor from the repo file
body = body.replace(/\(#shebang-detection\)/g, '(#shebang-detection)')
const rows = (body.match(/^\| `/gm) || []).length

const lines = []
lines.push('---')
lines.push('title: Supported formats')
lines.push(`description: The 224 formats jscpd ${version} tokenizes, with the extensions and shebangs that select them, generated from the FORMATS.md of the release.`)
lines.push('navigation:')
lines.push('  icon: i-lucide-languages')
lines.push('---')
lines.push('')
lines.push(`<!-- Generated by scripts/sync-formats-reference.mjs from FORMATS.md of jscpd ${version}. Edit the script or FORMATS.md in the jscpd repository, not this file. -->`)
lines.push('')
lines.push('jscpd picks a format for each file from its extension, its file name or its shebang line, and tokenizes the file with that format\'s comment and string rules. `jscpd --list` prints the names. A format with no extension of its own is still available: map it to an extension with `--formats-exts` or to a file name with `--formats-names`, as the examples in the tables show.')
lines.push('')
lines.push('```bash [Terminal]')
lines.push('jscpd --list                                   # the 224 format names')
lines.push('jscpd --formats-exts "javascript:es,es6" .    # treat .es and .es6 as JavaScript')
lines.push('jscpd --formats-names "docker:Dockerfile" .  # pick a format by file name')
lines.push('jscpd --format javascript,typescript .       # scan only these formats')
lines.push('```')
lines.push('')
lines.push(body.trim())
lines.push('')
writeFileSync(new URL('../content/4.reference/5.supported-formats.md', import.meta.url), lines.join('\n'))
console.log(`wrote content/4.reference/5.supported-formats.md: ${rows} table rows`)
