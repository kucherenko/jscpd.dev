#!/usr/bin/env node
/**
 * Writes content/4.reference/6.github-action.md from the action.yml of a
 * jscpd release, so the inputs table cannot drift:
 *
 *   node scripts/sync-action-reference.mjs path/to/action.yml 5.4.0
 *
 * action.yml is flat enough for a small line parser; no YAML dependency.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const [file, version = ''] = process.argv.slice(2)
if (!file) { console.error('usage: sync-action-reference.mjs action.yml [version]'); process.exit(1) }
const text = readFileSync(file, 'utf8')

function section(name) {
  const m = text.match(new RegExp(`^${name}:\\n([\\s\\S]*?)(?=^\\S|\\Z)`, 'm'))
  return m ? m[1] : ''
}
function entries(block) {
  const out = []
  let cur = null
  for (const line of block.split('\n')) {
    const key = line.match(/^  ([a-z][a-z0-9-]*):\s*$/)
    if (key) { cur = { name: key[1] }; out.push(cur); continue }
    const field = line.match(/^    ([a-z]+):\s*(.*)$/)
    if (cur && field) cur[field[1]] = field[2].replace(/^"(.*)"$/, '$1').replace(/^'(.*)'$/, '$1')
  }
  return out
}
const inputs = entries(section('inputs'))
const outputs = entries(section('outputs'))
if (inputs.length < 10) { console.error(`parsed only ${inputs.length} inputs`); process.exit(1) }
const esc = s => (s || '').replace(/\|/g, '\\|')
const def = v => (v === undefined || v === '' ? '—' : `\`${v}\``)

const lines = []
lines.push('---')
lines.push('title: GitHub Action')
lines.push(`description: The inputs and outputs of kucherenko/jscpd@v5, generated from the action.yml of jscpd ${version}.`)
lines.push('navigation:')
lines.push('  icon: i-lucide-github')
lines.push('---')
lines.push('')
lines.push(`<!-- Generated by scripts/sync-action-reference.mjs from action.yml of jscpd ${version}. Edit the script or action.yml in the jscpd repository, not this file. -->`)
lines.push('')
lines.push('`kucherenko/jscpd@v5` runs the same binary as the command line, so every input below is a [CLI option](/reference/cli) with the same name. The [CI guide](/guides/ci) shows the workflows; this page is the list.')
lines.push('')
lines.push('```yaml [.github/workflows/jscpd.yml]')
lines.push('- uses: kucherenko/jscpd@v5')
lines.push('  with:')
lines.push('    threshold: 3')
lines.push('```')
lines.push('')
lines.push('## Inputs')
lines.push('')
lines.push('| Input | What it does | Default |')
lines.push('|---|---|---|')
for (const i of inputs) lines.push(`| \`${i.name}\` | ${esc(i.description)} | ${def(i.default)} |`)
lines.push('')
lines.push('## Outputs')
lines.push('')
if (outputs.length) {
  lines.push('| Output | What it holds |')
  lines.push('|---|---|')
  for (const o of outputs) lines.push(`| \`${o.name}\` | ${esc(o.description)} |`)
} else {
  lines.push('The action sets no outputs.')
}
lines.push('')
lines.push('Read an output in a later step as `${{ steps.<id>.outputs.<name> }}` after giving the jscpd step an `id`.')
lines.push('')
writeFileSync(new URL('../content/4.reference/6.github-action.md', import.meta.url), lines.join('\n'))
console.log(`wrote content/4.reference/6.github-action.md: ${inputs.length} inputs, ${outputs.length} outputs`)
